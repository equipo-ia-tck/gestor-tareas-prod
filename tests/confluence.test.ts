import { describe, expect, it } from 'vitest';
import { htmlToText, pageChunks, pageIdFromName, parseConfluencePage } from '../src/domain/confluence';
import { unzip } from '../src/features/docs/unzip';

const PAGE = `<!DOCTYPE html><html><head><title>x</title></head><body>
  <h1 id="title-heading"><span id="title-text">Digital Sales &amp; Analytics : Owners de etiquetado</span></h1>
  <ol id="breadcrumbs">
    <li><span><a href="index.html">Digital Sales &amp; Analytics</a></span></li>
    <li><span><a href="261203121.html">🏠Home</a></span></li>
    <li><span><a href="3356558779.html">📐Etiquetado</a></span></li>
  </ol>
  <div id="main-content" class="wiki-content group">
    <h2>Modelo operativo</h2>
    <p>Cada <b>guía</b> tiene un owner que la valida antes de la entrega.</p>
    <ul><li>Paso 1</li><li>Paso 2</li></ul>
  </div>
  <div id="footer">Document generated by Confluence</div>
</body></html>`;

describe('parser de Confluence', () => {
  it('saca id, espacio, título, ruta, enlace y cuerpo de una página', () => {
    const p = parseConfluencePage(PAGE, 'Owners-de-etiquetado_4511892904.html')!;
    expect(p.id).toBe('4511892904');
    expect(p.space).toBe('Digital Sales & Analytics');
    expect(p.title).toBe('Owners de etiquetado');
    expect(p.path).toBe('Digital Sales & Analytics › 🏠Home › 📐Etiquetado › Owners de etiquetado');
    expect(p.url).toBe('https://confluence.cloud.lacaixa.es/confluence/pages/viewpage.action?pageId=4511892904');
    expect(p.body).toContain('Modelo operativo');
    expect(p.body).toContain('owner que la valida');
    expect(p.body).not.toContain('Document generated by'); // el footer no entra
    expect(p.body).not.toMatch(/<[a-z]/i); // sin HTML
  });

  it('el id sale del final del nombre, o del propio nombre si es numérico', () => {
    expect(pageIdFromName('Algo_123.html')).toBe('123');
    expect(pageIdFromName('456.html')).toBe('456');
  });

  it('htmlToText descodifica entidades y respeta listas', () => {
    const t = htmlToText('<p>a &amp; b</p><ul><li>uno</li><li>dos</li></ul>');
    expect(t).toContain('a & b');
    expect(t).toContain('- uno');
    expect(t).toContain('- dos');
    expect(t).not.toContain('&amp;');
  });

  it('descarta páginas sin cuerpo', () => {
    expect(parseConfluencePage('<span id="title-text">Espacio : Índice</span>', '1.html')).toBeNull();
  });

  it('trocea la página en chunks con fuente doc', () => {
    const chunks = pageChunks(parseConfluencePage(PAGE, 'x_99.html')!);
    expect(chunks.length).toBeGreaterThan(0);
    expect(chunks[0]).toMatchObject({ source: 'doc', ref: '99', title: 'Owners de etiquetado' });
  });
});

/** Construye un ZIP mínimo sin comprimir (método 0) con las entradas dadas, para probar `unzip`. */
function storedZip(files: { name: string; content: string }[]): ArrayBuffer {
  const enc = new TextEncoder();
  const locals: Uint8Array[] = [];
  const centrals: Uint8Array[] = [];
  let offset = 0;
  for (const f of files) {
    const name = enc.encode(f.name);
    const data = enc.encode(f.content);
    const lh = new DataView(new ArrayBuffer(30));
    lh.setUint32(0, 0x04034b50, true);
    lh.setUint16(26, name.length, true);
    lh.setUint32(18, data.length, true); // compSize
    lh.setUint32(22, data.length, true); // uncompSize
    const local = new Uint8Array(30 + name.length + data.length);
    local.set(new Uint8Array(lh.buffer), 0);
    local.set(name, 30);
    local.set(data, 30 + name.length);
    locals.push(local);

    const ch = new DataView(new ArrayBuffer(46));
    ch.setUint32(0, 0x02014b50, true);
    ch.setUint32(20, data.length, true); // compSize
    ch.setUint32(24, data.length, true); // uncompSize
    ch.setUint16(28, name.length, true);
    ch.setUint32(42, offset, true); // offset de la cabecera local
    const central = new Uint8Array(46 + name.length);
    central.set(new Uint8Array(ch.buffer), 0);
    central.set(name, 46);
    centrals.push(central);
    offset += local.length;
  }
  const cdSize = centrals.reduce((n, c) => n + c.length, 0);
  const eocd = new DataView(new ArrayBuffer(22));
  eocd.setUint32(0, 0x06054b50, true);
  eocd.setUint16(8, files.length, true);
  eocd.setUint16(10, files.length, true);
  eocd.setUint32(12, cdSize, true);
  eocd.setUint32(16, offset, true);
  const parts = [...locals, ...centrals, new Uint8Array(eocd.buffer)];
  const total = parts.reduce((n, p) => n + p.length, 0);
  const out = new Uint8Array(total);
  let at = 0;
  for (const p of parts) { out.set(p, at); at += p.length; }
  return out.buffer;
}

describe('unzip', () => {
  it('abre un zip y filtra por nombre', async () => {
    const zip = storedZip([{ name: 'a_1.html', content: '<i>hola</i>' }, { name: 'styles/site.css', content: 'body{}' }]);
    const entries = await unzip(zip, (n) => n.endsWith('.html'));
    expect(entries).toHaveLength(1);
    expect(entries[0].name).toBe('a_1.html');
    expect(entries[0].text).toBe('<i>hola</i>');
  });
});
